-- Schema-only migration for the Class Cancellation app.
--
-- Derived from the local SQLite database (class_cancellations.db):
--   programs: schedule rows imported from the Excel workbook
--   events: community events, indexed by start_date
--
-- The application also saves event JSON with price, instructor, and
-- registration. Those fields are nullable columns here so a later import
-- can keep them. JSON names map as follows:
--   startDate -> start_date
--   endDate   -> end_date
--   dateStr   -> date_str
--   timeStr   -> time_str
--
-- This migration creates empty tables. It does not copy rows, passwords,
-- API keys, or connection strings. Do not apply it to the hosted database
-- until a deliberate cutover. The running app keeps using SQLite and JSON.

create table public.programs (
  id bigint generated by default as identity primary key,
  sheet text,
  program text,
  program_id text,
  date_range text,
  "time" text,
  location text,
  class_room text,
  instructor text,
  program_status text,
  class_cancellation text,
  note text,
  withdrawal text,
  description text,
  fee text,
  session text,
  created_at timestamp default current_timestamp
);

comment on table public.programs is
  'Program schedule. Column set matches the existing SQLite programs table.';

create table public.events (
  id bigint generated by default as identity primary key,
  title text not null,
  start_date text not null,
  end_date text not null,
  description text,
  location text,
  date_str text,
  time_str text,
  image_url text,
  price text,
  instructor text,
  registration text
);

comment on table public.events is
  'Community events. Matches the SQLite events table, plus nullable JSON fields.';

create index idx_events_start_date on public.events (start_date);

alter table public.programs enable row level security;
alter table public.events enable row level security;

-- No policies are defined. anon and authenticated cannot read or write
-- these tables through the Data API. service_role keeps owner-equivalent
-- access for a future private import.
revoke all on table public.programs from anon, authenticated;
revoke all on table public.events from anon, authenticated;

revoke all on sequence public.programs_id_seq from anon, authenticated;
revoke all on sequence public.events_id_seq from anon, authenticated;
