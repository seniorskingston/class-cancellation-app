-- Permanent tables for the Class Cancellation app.
--
-- programs: one row per class from the Excel schedule
-- events: community calendar events edited in the app
-- app_settings: small values that must survive a restart, including visit counts
--
-- This script creates empty tables and the replace functions the backend calls.
-- It does not insert records and does not remove any existing file or SQLite data.
-- Run it once in the Supabase SQL Editor. The service role key is not stored here.

create table if not exists public.programs (
  id bigint generated by default as identity primary key,
  sheet text default '',
  program text default '',
  program_id text default '',
  date_range text default '',
  "time" text default '',
  location text default '',
  class_room text default '',
  instructor text default '',
  program_status text default '',
  class_cancellation text default '',
  note text default '',
  withdrawal text default '',
  description text default '',
  fee text default '',
  session text default '',
  created_at timestamptz default now()
);

create table if not exists public.events (
  id text primary key,
  title text not null default '',
  start_date text not null default '',
  end_date text not null default '',
  description text default '',
  location text default '',
  date_str text default '',
  time_str text default '',
  image_url text default '',
  price text default '',
  instructor text default '',
  registration text default '',
  sort_order integer not null default 0,
  updated_at timestamptz not null default now()
);

create index if not exists idx_events_start_date on public.events (start_date);
create index if not exists idx_events_sort_order on public.events (sort_order);

create table if not exists public.app_settings (
  key text primary key,
  value jsonb not null,
  updated_at timestamptz not null default now()
);

alter table public.programs enable row level security;
alter table public.events enable row level security;
alter table public.app_settings enable row level security;

revoke all on table public.programs from anon, authenticated;
revoke all on table public.events from anon, authenticated;
revoke all on table public.app_settings from anon, authenticated;

grant all on table public.programs to service_role;
grant all on table public.events to service_role;
grant all on table public.app_settings to service_role;
grant usage, select on all sequences in schema public to service_role;

-- Replaces program rows only when the new list is non-empty.
-- The delete and insert run in one transaction, so a failed insert keeps the old rows.
create or replace function public.replace_programs(rows jsonb)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  inserted_count integer := 0;
begin
  if rows is null or jsonb_typeof(rows) <> 'array' or jsonb_array_length(rows) = 0 then
    return 0;
  end if;

  delete from public.programs where id is not null;

  insert into public.programs (
    sheet, program, program_id, date_range, "time", location, class_room,
    instructor, program_status, class_cancellation, note, withdrawal,
    description, fee, session
  )
  select
    coalesce(x.sheet, ''),
    coalesce(x.program, ''),
    coalesce(x.program_id, ''),
    coalesce(x.date_range, ''),
    coalesce(x."time", ''),
    coalesce(x.location, ''),
    coalesce(x.class_room, ''),
    coalesce(x.instructor, ''),
    coalesce(x.program_status, ''),
    coalesce(x.class_cancellation, ''),
    coalesce(x.note, ''),
    coalesce(x.withdrawal, ''),
    coalesce(x.description, ''),
    coalesce(x.fee, ''),
    coalesce(x.session, '')
  from jsonb_to_recordset(rows) as x(
    sheet text,
    program text,
    program_id text,
    date_range text,
    "time" text,
    location text,
    class_room text,
    instructor text,
    program_status text,
    class_cancellation text,
    note text,
    withdrawal text,
    description text,
    fee text,
    session text
  );

  get diagnostics inserted_count = row_count;
  if inserted_count = 0 then
    raise exception 'Program import produced no rows; previous programs were kept';
  end if;
  return inserted_count;
end;
$$;

-- Replaces the event list in one transaction.
-- An empty list removes events only when allow_empty is true.
create or replace function public.replace_events(rows jsonb, allow_empty boolean default false)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  inserted_count integer := 0;
begin
  if rows is null or jsonb_typeof(rows) <> 'array' or jsonb_array_length(rows) = 0 then
    if allow_empty then
      delete from public.events where id is not null;
      return 0;
    end if;
    return 0;
  end if;

  delete from public.events where id is not null;

  insert into public.events (
    id, title, start_date, end_date, description, location, date_str, time_str,
    image_url, price, instructor, registration, sort_order, updated_at
  )
  select
    x.id,
    coalesce(x.title, ''),
    coalesce(x.start_date, ''),
    coalesce(x.end_date, ''),
    coalesce(x.description, ''),
    coalesce(x.location, ''),
    coalesce(x.date_str, ''),
    coalesce(x.time_str, ''),
    coalesce(x.image_url, ''),
    coalesce(x.price, ''),
    coalesce(x.instructor, ''),
    coalesce(x.registration, ''),
    coalesce(x.sort_order, 0),
    now()
  from jsonb_to_recordset(rows) as x(
    id text,
    title text,
    start_date text,
    end_date text,
    description text,
    location text,
    date_str text,
    time_str text,
    image_url text,
    price text,
    instructor text,
    registration text,
    sort_order integer
  );

  get diagnostics inserted_count = row_count;
  if inserted_count = 0 then
    raise exception 'Event import produced no rows; previous events were kept';
  end if;
  return inserted_count;
end;
$$;

revoke all on function public.replace_programs(jsonb) from public, anon, authenticated;
revoke all on function public.replace_events(jsonb, boolean) from public, anon, authenticated;
grant execute on function public.replace_programs(jsonb) to service_role;
grant execute on function public.replace_events(jsonb, boolean) to service_role;

notify pgrst, 'reload schema';
